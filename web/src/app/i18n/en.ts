/* manor web — English dictionary (translation of ja.ts, ADR-012 D8).
 *
 * The type below (`{ [K in TranslationKey]: MirrorEntry<K> }`) enforces, at compile
 * time, that this object has exactly the same key set as `ja.ts` (no missing key, no
 * extra key — excess-property checking on the object literal covers both
 * directions) — **and** that each entry is the same *kind* as its `ja.ts`
 * counterpart (a function stays a function, a string stays a string). That second
 * part matters for `t()`'s own type (`store.ts`): whether `params` is required is
 * decided from `ja.ts` alone, so if `en.ts` silently turned a function entry into a
 * plain string, `t()` would think params are still required while the English
 * branch quietly ignored them. `i18n/parity.test.ts` re-checks the key-set part at
 * runtime, as a safety net for any code path that bypasses the type system
 * (e.g. `as any`).
 *
 * Translated freely for natural English rather than word-for-word — meaning is
 * preserved, wording is not. Anywhere the original Japanese phrasing was unclear
 * enough that a faithful translation couldn't be made with confidence, it is
 * called out in the delivery report instead of guessed at.
 */
